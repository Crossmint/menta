/**
 * Builds the checkout card (an MCP Apps view) into one self-contained HTML
 * document, plus its secure-step script (Crossmint's React components) and
 * the Geist fonts, and writes them as a TypeScript module: the MCP server
 * serves the card as ui://oca/checkout-<hash>, and the web app
 * serves the script at /mcp/card/secure.js and the fonts at
 * /mcp/card/fonts/<file>. It also carries the package version, which the MCP
 * server reports as its own. Run by the package build; the output is gitignored.
 *
 * The card is drawn with the web app's own React components (src/ui) on
 * Preact (react → preact/compat), so it stays small, and its stylesheet is
 * Tailwind compiled from the same tokens (src/ui/theme.css).
 */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import tailwind from "@tailwindcss/postcss";
import { build, transform } from "esbuild";
import postcss from "postcss";

const here = (path) => fileURLToPath(new URL(path, import.meta.url));
const hash = (value, length = 16) =>
  createHash("sha256").update(value).digest("hex").slice(0, length);

/** Node built-ins some Crossmint dependencies mention but never use in browsers. */
const browserOnly = {
  name: "browser-only",
  setup(context) {
    context.onResolve(
      { filter: /^(crypto|stream|buffer|util|http|https|url|zlib)$/ },
      () => ({ path: "empty", namespace: "empty" }),
    );
    // CommonJS, so named imports resolve to undefined instead of failing.
    context.onLoad({ filter: /.*/, namespace: "empty" }, () => ({
      contents: "module.exports = {};",
      loader: "js",
    }));
  },
};

const secure = await build({
  entryPoints: [here("./secure-entry.tsx")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2020",
  platform: "browser",
  jsx: "automatic",
  write: false,
  legalComments: "none",
  define: {
    "process.env.NODE_ENV": '"production"',
    global: "globalThis",
  },
  plugins: [browserOnly],
  logLevel: "error",
});
const secureScript = secure.outputFiles[0].text;
const secureVersion = hash(secureScript);

// Geist (variable), served from our origin and named by content.
const fonts = {};
const fontFiles = {};
for (const [key, name, file] of [
  ["sans", "geist", "geist-sans/Geist-Variable.woff2"],
  ["mono", "geist-mono", "geist-mono/GeistMono-Variable.woff2"],
]) {
  const data = await readFile(here(`../node_modules/geist/dist/fonts/${file}`));
  const served = `${name}-${hash(data, 12)}.woff2`;
  fonts[key] = served;
  fontFiles[served] = data.toString("base64");
}

const script = await build({
  entryPoints: [here("./checkout-card.tsx")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2020",
  platform: "browser",
  jsx: "automatic",
  write: false,
  legalComments: "none",
  alias: {
    react: "preact/compat",
    "react-dom": "preact/compat",
    "react/jsx-runtime": "preact/jsx-runtime",
  },
  define: {
    "process.env.NODE_ENV": '"production"',
    __OCA_SECURE_VERSION__: JSON.stringify(secureVersion),
    __OCA_FONTS__: JSON.stringify(fonts),
  },
  logLevel: "error",
});
const js = script.outputFiles[0].text.trim();

const cssFile = here("./card.css");
const compiled = await postcss([tailwind()]).process(
  await readFile(cssFile, "utf8"),
  { from: cssFile },
);
const css = (
  await transform(compiled.css, {
    loader: "css",
    minify: true,
    target: "chrome100",
  })
).code.trim();

if (/<\/script/i.test(js) || /<\/style/i.test(css)) {
  throw new Error("The card's inline script or style would end its own tag.");
}

/** The server replaces __OCA_ORIGIN__ with its escaped origin when serving. */
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><meta name="oca-origin" content="__OCA_ORIGIN__"><title>Menta checkout</title><style>${css}</style></head><body><main id="card" aria-label="Menta checkout" aria-live="polite"></main><script>${js}</script></body></html>`;

// Hosts cache the card by its URI, so the URI carries the card's version.
const cardVersion = hash(html, 12);

const { version } = JSON.parse(await readFile(here("../package.json"), "utf8"));

await writeFile(
  here("../src/mcp/card.generated.ts"),
  [
    "// Generated by card/build.mjs from card/*. Do not edit.",
    `export const checkoutCardTemplate = ${JSON.stringify(html)};`,
    `export const checkoutCardVersion = ${JSON.stringify(cardVersion)};`,
    `export const checkoutCardSecureVersion = ${JSON.stringify(secureVersion)};`,
    `export const checkoutCardSecureScript = ${JSON.stringify(secureScript)};`,
    "/** The card's fonts by served file name, base64. */",
    `export const checkoutCardFonts: Record<string, string> = ${JSON.stringify(fontFiles)};`,
    `export const packageVersion = ${JSON.stringify(version)};`,
    "",
  ].join("\n"),
);
console.log(
  `checkout card: ${(html.length / 1024).toFixed(1)} KiB (script ${(js.length / 1024).toFixed(1)}, styles ${(css.length / 1024).toFixed(1)}), secure step script: ${(secureScript.length / 1024).toFixed(0)} KiB and fonts ${Object.keys(fontFiles).join(", ")} (loaded on demand)`,
);
